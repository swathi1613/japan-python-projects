from janome.tokenizer import Tokenizer

def analyze_japanese_text(text):
    tokenizer = Tokenizer()
    tokens = list(tokenizer.tokenize(text))

    print("--- JAPANESE TEXT ANALYSIS REPORT ---")
    print(f"Original Text: {text}")
    print(f"Total Words Detected: {len(tokens)}\n")

    print("Word Breakdown:")
    unique_kanji = set()

    for token in tokens:
        surface = token.surface
        part_of_speech = token.part_of_speech.split(',')[0]
        print(f" - Word: {surface} | Type: {part_of_speech}")

        for char in surface:
            if '\u4e00' <= char <= '\u9fa5':
                unique_kanji.add(char)

    print("\nUnique Kanji Characters Found:")
    print(", ".join(unique_kanji) if unique_kanji else "No Kanji found.")

# Direct Japanese text analysis
sample_text = "私はPythonと日本語を勉強しています。"
analyze_japanese_text(sample_text)

