import requests
from datetime import datetime

def convert_jpy(amount_jpy, target_currency="USD"):
    # Live currency exchange rates API
    url = "https://api.exchangerate-api.com/v4/latest/JPY"

    try:
        response = requests.get(url)
        data = response.json()

        rate = data['rates'].get(target_currency.upper())
        if not rate:
            print(f"Currency {target_currency} not supported.")
            return

        converted = amount_jpy * rate
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        log_entry = f"[{timestamp}] ¥{amount_jpy:,} JPY = ${converted:.2f} {target_currency.upper()} (Rate: {rate})\n"

        # Save to a local file
        with open("conversion_history.txt", "a", encoding="utf-8") as file:
            file.write(log_entry)

        print("--- CONVERSION SUCCESSFUL ---")
        print(log_entry.strip())
        print("Logged to 'conversion_history.txt'")

    except Exception as e:
        print(f"Error fetching exchange rates: {e}")

# Example Run: Convert 50,000 Yen to USD
convert_jpy(50000, "USD")

